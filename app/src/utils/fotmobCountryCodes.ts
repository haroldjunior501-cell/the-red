export function iso3ToIso2(code: string): string {
  const u = code.trim().toUpperCase();
  if (u.length === 2) return u;
  return ISO3_TO_ISO2[u] ?? u.slice(0, 2);
}

export function teamNameToIso2(name: string): string | null {
  const n = name.trim();
  if (NAME_TO_ISO2[n]) return NAME_TO_ISO2[n];
  const key = Object.keys(NAME_TO_ISO2).find((k) => k.toLowerCase() === n.toLowerCase());
  return key ? NAME_TO_ISO2[key] : null;
}
